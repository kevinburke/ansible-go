#!/usr/bin/env python3
"""Write the converged benchmark playbook that bench.sh times.

Every task is idempotent and reports "ok" once setup.yml has run, so the
timing measures per-task overhead rather than the work of changing a host.
The mix covers every module fastagent overrides: stat, file, copy, command,
shell, apt and systemd.

Usage: gen_playbook.py OUTDIR [TASKS]
"""
import argparse
import os
import sys

DIR = "/tmp/fastagent-bench"

# (module, count weight). Order within the playbook is interleaved so a run
# of identical tasks does not flatter any one code path.
MIX = [
    ("stat", 90),
    ("file", 50),
    ("copy", 50),
    ("command", 40),
    ("shell", 10),
    ("apt", 5),
    ("systemd", 5),
]


def task(kind: str, i: int) -> str:
    n = f"{i:03d}"
    if kind == "stat":
        return f"""- name: stat {n}
  stat:
    path: {DIR}/file-{i % 25:02d}
"""
    if kind == "file":
        return f"""- name: file directory {n}
  file:
    path: {DIR}/dir-{i % 25:02d}
    state: directory
    mode: "0755"
"""
    if kind == "copy":
        return f"""- name: copy content {n}
  copy:
    dest: {DIR}/file-{i % 25:02d}
    content: "fastagent benchmark {i % 25:02d}\\n"
    mode: "0644"
"""
    if kind == "command":
        return f"""- name: command {n}
  command: /bin/true
  changed_when: false
"""
    if kind == "shell":
        return f"""- name: shell {n}
  shell: test -d {DIR}
  changed_when: false
"""
    if kind == "apt":
        return f"""- name: apt present {n}
  apt:
    name: ca-certificates
    state: present
"""
    if kind == "systemd":
        return f"""- name: systemd started {n}
  systemd:
    name: ssh
    state: started
"""
    raise ValueError(kind)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("outdir")
    ap.add_argument("tasks", nargs="?", type=int, default=250)
    args = ap.parse_args()

    total = sum(w for _, w in MIX)
    counts = {k: args.tasks * w // total for k, w in MIX}
    # Rounding down leaves a remainder; give it to stat so the total is exact.
    counts["stat"] += args.tasks - sum(counts.values())

    queues = {k: [task(k, i) for i in range(c)] for k, c in counts.items()}
    ordered = []
    while any(queues.values()):
        for k, _ in MIX:
            if queues[k]:
                ordered.append(queues[k].pop(0))
    assert len(ordered) == args.tasks, (len(ordered), args.tasks)

    os.makedirs(args.outdir, exist_ok=True)
    header = """---
# Generated by scripts/bench/gen_playbook.py; do not edit.
- hosts: bench
  gather_facts: false
  tasks:
"""
    with open(os.path.join(args.outdir, "bench.yml"), "w") as f:
        f.write(header)
        for t in ordered:
            f.write("".join("    " + line + "\n" for line in t.splitlines()))

    setup = f"""---
# Generated by scripts/bench/gen_playbook.py; do not edit.
- hosts: bench
  gather_facts: false
  tasks:
    - name: bench directory
      file:
        path: {DIR}
        state: directory
        mode: "0755"
"""
    for i in range(25):
        setup += f"""    - name: bench dir {i:02d}
      file:
        path: {DIR}/dir-{i:02d}
        state: directory
        mode: "0755"
    - name: bench file {i:02d}
      copy:
        dest: {DIR}/file-{i:02d}
        content: "fastagent benchmark {i:02d}\\n"
        mode: "0644"
"""
    with open(os.path.join(args.outdir, "setup.yml"), "w") as f:
        f.write(setup)

    teardown = f"""---
# Generated by scripts/bench/gen_playbook.py; do not edit.
- hosts: bench
  gather_facts: false
  tasks:
    - name: remove bench directory
      file:
        path: {DIR}
        state: absent
"""
    with open(os.path.join(args.outdir, "teardown.yml"), "w") as f:
        f.write(teardown)
    return 0


if __name__ == "__main__":
    sys.exit(main())
